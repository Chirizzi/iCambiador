function detectLocale(){
  const params = new URLSearchParams(location.search);
  const forced = params.get('lang');
  if(forced && TRANSLATIONS[forced]){
    localStorage.setItem('achou-trocador:locale', forced);
    return forced;
  }
  const saved = localStorage.getItem('achou-trocador:locale');
  if(saved && TRANSLATIONS[saved]) return saved;
  const langs = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || 'en'];
  for(const l of langs){
    const code = l.slice(0, 2).toLowerCase();
    if(TRANSLATIONS[code]) return code;
  }
  return 'en';
}

const LOCALE = detectLocale();

function t(key, vars){
  const dict = TRANSLATIONS[LOCALE] || TRANSLATIONS.en;
  let str = dict[key] ?? TRANSLATIONS.en[key] ?? key;
  if(vars){
    for(const k in vars){
      str = str.replace(new RegExp(`{{${k}}}`, 'g'), vars[k]);
    }
  }
  return str;
}

function applyStaticTranslations(){
  document.documentElement.lang = LOCALE === 'pt' ? 'pt-BR' : LOCALE;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder));
  });
  document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
    el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel));
  });
  const titleEl = document.querySelector('title');
  if(titleEl) titleEl.textContent = t('app.title');
  const descEl = document.querySelector('meta[name="description"]');
  if(descEl) descEl.setAttribute('content', t('app.description'));
  const appleTitleEl = document.querySelector('meta[name="apple-mobile-web-app-title"]');
  if(appleTitleEl) appleTitleEl.setAttribute('content', APP_NAME);
}

document.addEventListener('DOMContentLoaded', applyStaticTranslations);
